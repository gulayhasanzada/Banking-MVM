CREATE TABLE channel.customer_session (
    customer_session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id BIGINT REFERENCES customer.party(party_id),
    channel_id BIGINT NOT NULL REFERENCES channel.channel(channel_id),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMPTZ,
    source_system TEXT NOT NULL,
    source_session_id TEXT NOT NULL,
