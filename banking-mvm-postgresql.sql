CREATE TABLE ref.currency (
    currency_code CHAR(3) PRIMARY KEY,
    currency_name TEXT NOT NULL,
    minor_unit SMALLINT NOT NULL CHECK (minor_unit BETWEEN 0 AND 4),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE ref.country (
    country_code CHAR(2) PRIMARY KEY,
    country_name TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE ref.product_type (
    product_type_code TEXT PRIMARY KEY,
    product_domain TEXT NOT NULL,
    product_name TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (product_domain, product_name)
);

CREATE TABLE ledger.legal_entity (
    legal_entity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_code TEXT NOT NULL UNIQUE,
    legal_name TEXT NOT NULL,
    country_code CHAR(2) REFERENCES ref.country(country_code),
    lei TEXT UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ledger.accounting_period (
    accounting_period_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_entity_id BIGINT NOT NULL REFERENCES ledger.legal_entity(legal_entity_id),
    period_code TEXT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    period_status TEXT NOT NULL CHECK (period_status IN ('open', 'closed', 'locked')),
    CHECK (end_date >= start_date),
    UNIQUE (legal_entity_id, period_code)
);

CREATE TABLE ledger.gl_account (
    gl_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_entity_id BIGINT NOT NULL REFERENCES ledger.legal_entity(legal_entity_id),
    account_code TEXT NOT NULL,
    account_name TEXT NOT NULL,
    account_type TEXT NOT NULL CHECK (account_type IN ('asset', 'liability', 'equity', 'income', 'expense')),
    parent_gl_account_id BIGINT REFERENCES ledger.gl_account(gl_account_id),
    is_postable BOOLEAN NOT NULL DEFAULT TRUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (legal_entity_id, account_code)
);

CREATE TABLE customer.party (
    party_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_type TEXT NOT NULL CHECK (party_type IN ('individual', 'corporation', 'partnership', 'trust', 'government', 'other')),
    legal_name_ciphertext BYTEA NOT NULL,
    domicile_country_code CHAR(2) REFERENCES ref.country(country_code),
    lifecycle_status TEXT NOT NULL CHECK (lifecycle_status IN ('prospect', 'active', 'dormant', 'deceased', 'closed', 'merged')),
    cif_number TEXT UNIQUE,
    primary_legal_entity_id BIGINT REFERENCES ledger.legal_entity(legal_entity_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customer.individual_profile (
    party_id BIGINT PRIMARY KEY REFERENCES customer.party(party_id) ON DELETE RESTRICT,
    birth_date_ciphertext BYTEA,
    citizenship_country_code CHAR(2) REFERENCES ref.country(country_code),
    preferred_language TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customer.corporate_profile (
    party_id BIGINT PRIMARY KEY REFERENCES customer.party(party_id) ON DELETE RESTRICT,
    incorporation_date DATE,
    lei TEXT UNIQUE,
    duns_number TEXT UNIQUE,
    industry_code TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customer.party_identifier (
    party_identifier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id BIGINT NOT NULL REFERENCES customer.party(party_id),
    identifier_type TEXT NOT NULL,
    issuing_country_code CHAR(2) REFERENCES ref.country(country_code),
    identifier_ciphertext BYTEA NOT NULL,
    value_fingerprint BYTEA NOT NULL,
    valid_from DATE,
    valid_to DATE,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from),
    UNIQUE (identifier_type, issuing_country_code, value_fingerprint)
);

CREATE TABLE customer.party_address (
    party_address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id BIGINT NOT NULL REFERENCES customer.party(party_id),
    address_type TEXT NOT NULL,
    address_ciphertext BYTEA NOT NULL,
    country_code CHAR(2) REFERENCES ref.country(country_code),
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_to DATE,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE TABLE customer.party_contact (
    party_contact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id BIGINT NOT NULL REFERENCES customer.party(party_id),
    contact_type TEXT NOT NULL CHECK (contact_type IN ('email', 'phone', 'other')),
    contact_ciphertext BYTEA NOT NULL,
    value_fingerprint BYTEA,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customer.party_relationship (
    party_relationship_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_party_id BIGINT NOT NULL REFERENCES customer.party(party_id),
    to_party_id BIGINT NOT NULL REFERENCES customer.party(party_id),
    relationship_type TEXT NOT NULL,
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_to DATE,
    CHECK (from_party_id <> to_party_id),
    CHECK (valid_to IS NULL OR valid_to >= valid_from),
    UNIQUE (from_party_id, to_party_id, relationship_type, valid_from)
);

