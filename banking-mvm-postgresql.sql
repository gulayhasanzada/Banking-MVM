);

CREATE TABLE channel.branch (
    branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code TEXT NOT NULL UNIQUE,
    branch_name TEXT NOT NULL,
    legal_entity_id BIGINT REFERENCES ledger.legal_entity(legal_entity_id),
    country_code CHAR(2) REFERENCES ref.country(country_code),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
