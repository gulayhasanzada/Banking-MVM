CREATE TABLE account.deposit_account (
    deposit_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_entity_id BIGINT NOT NULL REFERENCES ledger.legal_entity(legal_entity_id),
    branch_id BIGINT REFERENCES channel.branch(branch_id),
    product_type_code TEXT NOT NULL REFERENCES ref.product_type(product_type_code),
    currency_code CHAR(3) NOT NULL REFERENCES ref.currency(currency_code),
    account_number_ciphertext BYTEA NOT NULL,
    account_number_fingerprint BYTEA NOT NULL UNIQUE,
    account_number_last4 CHAR(4),
    account_status TEXT NOT NULL CHECK (account_status IN ('pending_opening', 'active', 'dormant', 'frozen', 'restricted', 'closed')),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    source_system TEXT NOT NULL,
    source_account_id TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_system, source_account_id),
    CHECK (closed_at IS NULL OR closed_at >= opened_at)
);

CREATE TABLE account.account_holder (
    deposit_account_id BIGINT NOT NULL REFERENCES account.deposit_account(deposit_account_id),
    party_id BIGINT NOT NULL REFERENCES customer.party(party_id),
    holder_role TEXT NOT NULL CHECK (holder_role IN ('owner', 'joint_owner', 'signatory', 'custodian', 'beneficial_owner')),
    valid_from DATE NOT NULL DEFAULT CURRENT_DATE,
    valid_to DATE,
    PRIMARY KEY (deposit_account_id, party_id, holder_role, valid_from),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

